import { randomUUID } from "node:crypto";
import type { NextApiRequest, NextApiResponse } from "next";
import { createRouter } from "next-connect";
import { z } from "zod";
import controller from "infra/controller";
import { NotFoundError, ValidationError } from "infra/errors";
import { sandboxEnabled } from "infra/runtime";
import { captureAppmaxInstallation } from "models/appmax_installation";

const optionalCallbackValue = z
  .string()
  .min(1)
  .max(4096)
  .optional()
  .catch(undefined);

const healthCheck = z.object({
  // Appmax's public validator sends this placeholder instead of a numerical ID.
  app_id: z.union([z.number().int().positive(), z.literal("DEMO_APP_ID")]),
  external_key: optionalCallbackValue,
  client_key: optionalCallbackValue,
  client_id: optionalCallbackValue,
  client_secret: optionalCallbackValue,
});

export const config = { api: { bodyParser: { sizeLimit: "16kb" } } };

async function postHandler(req: NextApiRequest, res: NextApiResponse) {
  res.setHeader("Cache-Control", "no-store");
  const appId = Number(process.env.APPMAX_APPSTORE_NUMERIC_ID);
  if (
    !sandboxEnabled() ||
    process.env.VERCEL_ENV === "production" ||
    !Number.isSafeInteger(appId) ||
    appId < 1
  ) {
    throw new NotFoundError({
      message: "Appmax installation validation is unavailable.",
      action: "Check the sandbox validation URL and try again.",
    });
  }

  const parsed = healthCheck.safeParse(req.body);
  if (
    !parsed.success ||
    (parsed.data.app_id !== "DEMO_APP_ID" && parsed.data.app_id !== appId)
  ) {
    throw new ValidationError({
      message: "Invalid Appmax installation validation request.",
      action: "Check the Appmax numerical application ID.",
    });
  }

  const { app_id, external_key, client_key, client_id, client_secret } =
    parsed.data;
  const installationKey = external_key ?? client_key;
  const credentials =
    client_id && client_secret ? { client_id, client_secret } : undefined;
  // Only a matching pending attempt can capture a UUID. Checkout stays unchanged
  // until the operator verifies the credentials generated by Appmax.
  if (
    app_id === appId &&
    installationKey &&
    (!external_key || !client_key || external_key === client_key)
  ) {
    const externalId = await captureAppmaxInstallation(
      installationKey,
      credentials,
    );
    if (externalId) return res.status(200).json({ external_id: externalId });
  }
  return res.status(200).json({ external_id: randomUUID() });
}

export default createRouter<NextApiRequest, NextApiResponse>()
  .post(postHandler)
  .handler(controller.errorHandlers);
